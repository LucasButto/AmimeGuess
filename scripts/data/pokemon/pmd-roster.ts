export function presentationFor(name: string, zone: 'ground' | 'sky'): PresentationDecision & { movement: Movement } {
  const decision = PMD_DECISIONS[name];
  return { zone, locomotion: 'Walk', movement: movementFor(name), ...decision };
}
export function movementFor(name: string): Movement {
  if (['Raikou', 'Entei', 'Suicune', 'Ponyta', 'Rapidash', 'Lillipup', 'Stoutland', 'Mudbray', 'Mudsdale', 'Cyclizar'].includes(name)) return 'run';
  if (['Diglett', 'Dugtrio'].includes(name)) return 'burrow';
  if (['Voltorb', 'Electrode'].includes(name)) return 'roll';
  if (name === 'Spinda') return 'stagger';
  if (name === 'Zigzagoon') return 'zigzag';
  if (name === 'Hoppip') return 'drift';
  if (name === 'Magikarp') return 'hop';
  if (['Porygon', 'Porygon2', 'Porygon-Z'].includes(name)) return 'hover';
  return 'walk';
}

